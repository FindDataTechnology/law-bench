"""Slot model for document templates.

A *slot* is a named placeholder written as ``{{slot_name}}`` in document text.
Slots generated by :mod:`src.generator.generator` are written as their own run with a
yellow highlight so they are easy to spot and fill - either by a human in Word
or programmatically via :func:`fill_slots`.

The helpers here operate on a ``python-docx`` :class:`~docx.document.Document`,
accepting either an open document or a path to a ``.docx`` file.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Iterator, Union

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.text.paragraph import Paragraph

__all__ = [
    "SLOT_PATTERN",
    "SLOT_NAME_RE",
    "SlotValueError",
    "slot_token",
    "find_slots",
    "fill_slots",
]

# A slot token: ``{{ name }}`` with optional inner whitespace. The captured
# group is the slot name (Unicode word chars + dash; CJK names like
# ``{{工作内容}}`` are valid — LLM-generated clauses emit them, and the
# coherence gate / extractor / filler must all see the same set of slots).
SLOT_PATTERN = re.compile(r"\{\{\s*([\w][\w-]*)\s*\}\}")

# A bare slot name (used to validate names passed to :func:`slot_token`).
SLOT_NAME_RE = re.compile(r"[\w][\w-]*")

# Run-level child tags whose text content we treat as "run text" and clear when
# rewriting a run.
_TEXT_TAGS = (qn("w:t"), qn("w:br"), qn("w:cr"))


class SlotValueError(ValueError):
    """Raised by :func:`fill_slots` (``strict=True``) when values are missing."""


DocumentLike = Union[str, Path, "object"]


def slot_token(name: str) -> str:
    """Return the ``{{name}}`` placeholder string for ``name``.

    Raises :class:`ValueError` if ``name`` is not a valid slot name.
    """
    if not isinstance(name, str) or not SLOT_NAME_RE.fullmatch(name):
        raise ValueError(f"invalid slot name: {name!r}")
    return "{{" + name + "}}"


def _open_document(doc: DocumentLike):
    """Return an open document, loading from a path when given a path/str."""
    if isinstance(doc, (str, Path)):
        return Document(str(doc))
    return doc  # assume an already-open Document


def _iter_paragraphs(document) -> Iterator[Paragraph]:
    """Yield body paragraphs and paragraphs nested inside table cells."""
    yield from document.paragraphs
    for table in getattr(document, "tables", []) or []:
        for row in table.rows:
            for cell in row.cells:
                yield from cell.paragraphs


def find_slots(doc: DocumentLike) -> list[str]:
    """Return the de-duplicated slot names in ``doc`` in first-appearance order.

    ``doc`` may be a path/str or an open :class:`~docx.document.Document`.
    """
    seen: dict[str, None] = {}
    document = _open_document(doc)
    for paragraph in _iter_paragraphs(document):
        for name in SLOT_PATTERN.findall(paragraph.text):
            if name not in seen:
                seen[name] = None
    return list(seen)


# --------------------------------------------------------------------------- #
# Low-level run helpers (shared with :mod:`src.generator.generator`).
# --------------------------------------------------------------------------- #
def _make_text(text: str):
    el = OxmlElement("w:t")
    el.text = text
    el.set(qn("xml:space"), "preserve")
    return el


def _make_break():
    return OxmlElement("w:br")


def _clear_run_text(run) -> None:
    """Remove all text/break children from ``run`` while preserving its rPr."""
    r = run._r
    for child in list(r):
        if child.tag in _TEXT_TAGS:
            r.remove(child)


def set_run_text(run, text: str) -> None:
    """Set ``run``'s text, mapping ``\\n`` to line breaks (``<w:br/>``).

    The run's formatting (rPr) is preserved; only text/break children change.
    """
    _clear_run_text(run)
    lines = text.split("\n")
    r = run._r
    r.append(_make_text(lines[0]))
    for line in lines[1:]:
        r.append(_make_break())
        r.append(_make_text(line))


def clear_highlight(run) -> None:
    """Remove any ``<w:highlight>`` from the run's formatting, if present."""
    rPr = run._r.find(qn("w:rPr"))
    if rPr is None:
        return
    hl = rPr.find(qn("w:highlight"))
    if hl is not None:
        rPr.remove(hl)


def _sub_with_values(text: str, values: dict[str, str]):
    """Return ``(new_text, count)`` after substituting valued slot tokens."""

    def _repl(m: re.Match) -> str:
        return values.get(m.group(1), m.group(0))

    return SLOT_PATTERN.subn(_repl, text)


def _fill_paragraph(paragraph: Paragraph, values: dict[str, str]) -> int:
    """Replace valued slot tokens in ``paragraph``; return count replaced.

    Tokens fully contained in a single run are replaced in place (preserving
    formatting and clearing the slot highlight). Tokens that straddle runs are
    handled by rebuilding the paragraph runs from concatenated text, which may
    flatten intra-paragraph formatting on that paragraph.
    """
    text = paragraph.text
    if "{{" not in text:
        return 0
    valued = [m for m in SLOT_PATTERN.finditer(text) if m.group(1) in values]
    if not valued:
        return 0

    # In-place replacement for tokens that live inside a single run.
    for run in paragraph.runs:
        if not SLOT_PATTERN.search(run.text):
            continue
        new_text, _ = _sub_with_values(run.text, values)
        if new_text != run.text:
            set_run_text(run, new_text)
            # Drop the placeholder highlight once the slot is fully filled.
            if not SLOT_PATTERN.search(new_text):
                clear_highlight(run)

    # Any token still present must span runs -> rebuild the paragraph.
    if SLOT_PATTERN.search(paragraph.text):
        new_text, _ = _sub_with_values(paragraph.text, values)
        _rebuild_runs(paragraph, new_text)

    return len(valued)


def _rebuild_runs(paragraph: Paragraph, new_text: str) -> None:
    """Rewrite ``paragraph`` so all its text is in the first run (its format)."""
    runs = paragraph.runs
    if not runs:
        set_run_text(paragraph.add_run(), new_text)
        return
    set_run_text(runs[0], new_text)
    for run in runs[1:]:
        run._r.getparent().remove(run._r)


def fill_slots(doc, values, *, strict: bool = False) -> int:
    """Replace ``{{slot}}`` tokens in ``doc`` with ``values``; return count.

    ``doc`` may be a path/str (the file is saved in place) or an open document
    (the caller is responsible for saving).

    By default tokens without a provided value are left untouched (enabling
    partial fills). With ``strict=True`` a :class:`SlotValueError` is raised
    listing any slot present in the document but missing from ``values``.
    Multi-line values (containing ``\\n``) insert line breaks.
    """
    document = _open_document(doc)
    values = {str(k): str(v) for k, v in (values or {}).items()}

    if strict:
        present = find_slots(document)
        missing = [name for name in present if name not in values]
        if missing:
            raise SlotValueError(
                "missing values for slots: " + ", ".join(sorted(missing))
            )

    count = 0
    for paragraph in _iter_paragraphs(document):
        count += _fill_paragraph(paragraph, values)

    if isinstance(doc, (str, Path)):
        document.save(str(doc))
    return count
