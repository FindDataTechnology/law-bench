"""Contract template definitions per contract class.

A contract template is Markdown content with ``{{slot}}`` placeholders (reusing
the ``document-generation`` slot token model). Templates and their slot
instructions are generated by ``scripts/seed_contract_templates.py`` into the
committed registry ``src/contracts/data/contracts.json``.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from src.generator import SLOT_PATTERN
from src.eval.errors import NotFoundError

_HERE = Path(__file__).resolve().parent
_REGISTRY_PATH = _HERE / "data" / "contracts.json"
# src/contracts -> src -> repo root
_REPO_ROOT = _HERE.parents[1]
# Canonical (committed) law-info source: output/law_info is gitignored and absent
# in the container, so read the bundled markdown under src/eval/seed/law_info.
_LAW_INFO_DIR = _REPO_ROOT / "src" / "eval" / "seed" / "law_info"
_CONTRACT_TYPES_PATH = _LAW_INFO_DIR / "contract_types.json"


@lru_cache(maxsize=1)
def _registry() -> dict[str, dict]:
    """Load and cache the contract template registry keyed by contract type."""
    with _REGISTRY_PATH.open(encoding="utf-8") as fh:
        data = json.load(fh)
    return {entry["key"]: entry for entry in data}


def list_contract_types() -> list[dict]:
    """Return the supported contract classes as ``[{key, zh}]`` in file order."""
    with _CONTRACT_TYPES_PATH.open(encoding="utf-8") as fh:
        return json.load(fh)


def get_template(contract_type: str) -> dict:
    """Return ``{type, zh_name, body, slots}`` for ``contract_type``.

    ``slots`` is the de-duplicated list of ``{{slot}}`` names in ``body`` in
    first-appearance order. Raises :class:`NotFoundError` for an unknown type.
    """
    entry = _registry().get(contract_type)
    if entry is None:
        raise NotFoundError(f"unknown contract type: {contract_type!r}")
    body = entry["body"]
    slots: list[str] = list(dict.fromkeys(SLOT_PATTERN.findall(body)))
    return {
        "type": entry["key"],
        "zh_name": entry["zh"],
        "body": body,
        "slots": slots,
    }


def normalize_body(raw: str, required_slots: list[str]) -> str:
    """Normalize an LLM-drafted contract body to guarantee slot consistency.

    Strips a surrounding code fence and a leading H1 title line, removes any
    ``{{slot}}`` tokens not in ``required_slots``, and appends a ``## 签署信息``
    block with any missing required slots. The result's slot set equals
    ``set(required_slots)``.
    """
    text = (raw or "").strip()
    # strip a surrounding ```...``` fence
    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines).strip()
    # strip a leading H1 title line (contract sections use ## headings)
    lines = text.splitlines()
    if lines and lines[0].lstrip().startswith("# ") and not lines[0].lstrip().startswith("## "):
        lines = lines[1:]
        text = "\n".join(lines).lstrip("\n")
    required = set(required_slots)

    # The drafter occasionally writes a slot token with separators it copied
    # from the law context (e.g. ``{{交付/登记}}``). SLOT_PATTERN (``\w+``) won't
    # match such a token, so it would survive ``_strip_unknown`` unchanged and
    # not be counted as present, causing the slot to be (wrongly) appended to
    # 签署信息. Sanitize separator-bearing tokens to their ``\w+`` form when that
    # form is a required slot, so the placeholder stays fillable and slot-set
    # consistency holds.
    _sep_slot_re = re.compile(r"\{\{([^{}]+?)\}\}")

    def _sanitize_sep(m: "re.Match[str]") -> str:
        raw = m.group(1).strip()
        if re.fullmatch(r"[\w-]+", raw):
            return m.group(0)  # already a clean token; leave for _strip_unknown
        cleaned = re.sub(r"[^\w-]+", "", raw)
        if cleaned and cleaned in required:
            return "{{" + cleaned + "}}"
        return m.group(0)

    text = _sep_slot_re.sub(_sanitize_sep, text)

    def _strip_unknown(m: "re.Match[str]") -> str:
        return "" if m.group(1) not in required else m.group(0)

    text = SLOT_PATTERN.sub(_strip_unknown, text)
    # append any missing required slots so the manifest stays consistent
    present = set(SLOT_PATTERN.findall(text))
    missing = [s for s in required_slots if s not in present]
    if missing:
        text = text.rstrip() + "\n\n## 签署信息\n\n" + "\n".join("{{" + s + "}}" for s in missing) + "\n"
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()
